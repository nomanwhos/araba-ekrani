"""Writes Torpido's Swift theme and colour assets from replica/design/tokens.json.

tokens.json is the single source. Run after every token change, then run
contrast.py (replica-design) on the same file:

    python3 scripts/gen_theme.py
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
TOKENS = ROOT / "replica" / "design" / "tokens.json"
SWIFT_OUT = ROOT / "App" / "Design" / "Theme.generated.swift"
ASSETS = ROOT / "App" / "Assets.xcassets"

# Roles that also exist as asset colour sets (AccentColor drives the system tint).
ASSET_ROLES = {"accent": "AccentColor", "bg": "Night", "surface": "NightRaised"}


def camel(name):
    head, *rest = re.split(r"[-_]", name)
    return head + "".join(part.capitalize() for part in rest)


def rgb(hex_value):
    h = hex_value.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def colour_line(role, value):
    if role in ASSET_ROLES:
        return f'    static let {camel(role)} = Color("{ASSET_ROLES[role]}")'
    r, g, b = (round(c / 255, 4) for c in rgb(value))
    return f"    static let {camel(role)} = Color(red: {r}, green: {g}, blue: {b})"


def write_colorset(asset_name, value):
    r, g, b = rgb(value)
    folder = ASSETS / f"{asset_name}.colorset"
    folder.mkdir(parents=True, exist_ok=True)
    contents = {
        "colors": [{
            "color": {"color-space": "srgb", "components": {
                "alpha": "1.000", "red": f"0x{r:02X}", "green": f"0x{g:02X}", "blue": f"0x{b:02X}"}},
            "idiom": "universal",
        }],
        "info": {"author": "xcode", "version": 1},
    }
    (folder / "Contents.json").write_text(json.dumps(contents, indent=2) + "\n", encoding="utf-8")


def numbers_enum(name, values, doc):
    lines = [f"    /// {doc}", f"    enum {name} {{"]
    lines += [f"        static let {camel(k)}: CGFloat = {v}" for k, v in values.items()]
    lines.append("    }")
    return lines


def main():
    tokens = json.loads(TOKENS.read_text(encoding="utf-8"))
    colours = tokens["color"]
    lines = [
        "// Generated by scripts/gen_theme.py from replica/design/tokens.json. Do not edit by hand.",
        "import SwiftUI",
        "",
        "enum Theme {",
        *[colour_line(role, value) for role, value in colours.items()],
        "",
        *numbers_enum("Space", {f"s{v}": v for v in tokens["space"] if v}, "Spacing scale, points."),
        "",
        *numbers_enum("Radius", {k: v for k, v in tokens["radius"].items()}, "Corner radii, points."),
        "",
        *numbers_enum("Size", tokens["size"], "Fixed sizes, points. Scale with @ScaledMetric where text-adjacent."),
        "}",
        "",
    ]
    SWIFT_OUT.parent.mkdir(parents=True, exist_ok=True)
    SWIFT_OUT.write_text("\n".join(lines), encoding="utf-8")
    for role, asset in ASSET_ROLES.items():
        write_colorset(asset, colours[role])
    print(f"wrote {SWIFT_OUT.relative_to(ROOT)} and {len(ASSET_ROLES)} colour sets")


if __name__ == "__main__":
    main()
